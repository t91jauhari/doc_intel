import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'frontend/package.json'));
const {chromium}=require('@playwright/test');
const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || (process.platform==='win32'?'msedge':undefined)});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto('http://localhost:3000/login');
 await page.getByLabel('Organization',{exact:true}).fill(process.env.DEV_ORGANIZATION||'sqe');
 await page.getByLabel('Email address',{exact:true}).fill(process.env.DEV_EMAIL||'sqe@bic.local');
 await page.getByLabel('Password',{exact:true}).fill(process.env.DEV_PASSWORD||'P@ssw0rd2026');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.waitForURL('http://localhost:3000/');
 await page.goto('http://localhost:3000/settings');
 await page.getByRole('button',{name:'Document profiles',exact:true}).click();
 await page.getByRole('heading',{name:'Profile fields and schema'}).waitFor();
 await page.locator('summary').filter({hasText:'Add a new field'}).click();
 await page.getByLabel('Field key',{exact:false}).fill('ui_test_observation');
 await page.getByLabel('Display label',{exact:true}).fill('UI test observation');
 await page.getByLabel('Extraction instruction',{exact:true}).fill('Transcribe this labeled field only. Null when blank.');
 await page.getByRole('button',{name:'Add profile field',exact:true}).click();
 await page.getByText('Unpublished changes',{exact:true}).first().waitFor();
 const settingsVisible=await page.getByText('ui_test_observation',{exact:true}).count();
 if(!settingsVisible)throw Error('Added field not visible in draft');
 page.on('dialog',d=>d.accept());
 const listing=await (await page.request.get('http://localhost:3000/api/cases?limit=100')).json();
 let caseId=process.env.FIELD_UI_CASE_ID;
 if(!caseId){for(const item of listing.items||[]){const detail=await(await page.request.get(`http://localhost:3000/api/cases/${item.id}`)).json();if(detail.documents?.some(d=>d.status==='COMPLETED')){caseId=item.id;break;}}}
 if(!caseId)throw Error('Provide FIELD_UI_CASE_ID for a case with completed extraction.');
 await page.goto(`http://localhost:3000/cases/${caseId}`);
 await page.getByText('Reprocess selected fields',{exact:true}).first().click();
 await page.getByRole('textbox',{name:/^Reason/}).fill('UI smoke check');
 const checks=page.locator('.field-catalogue input[type=checkbox]');
 await checks.first().check();
 if(!await page.getByRole('button',{name:'Reprocess selected fields',exact:true}).isEnabled())throw Error('Reprocess button not enabled for selected field');
 const workspace=page.locator('.reprocess-workspace').filter({has:page.getByRole('button',{name:'Reprocess selected fields',exact:true})}).first();
 const save=workspace.getByRole('checkbox',{name:/Save guidance to this document profile/});
 if(!await save.isChecked())throw Error('Reusable profile guidance must default on for administrator');
 await workspace.getByRole('textbox',{name:/Additional extraction guidance/}).fill('Inspect the labeled box and every continuation line.');
 await workspace.locator('summary').filter({hasText:'Profile and correction options'}).click();
 const latest=workspace.getByRole('checkbox',{name:/Use latest published profile instructions/});
 if(!await latest.isChecked()||!await latest.isDisabled())throw Error('Saved guidance must use latest profile');
 await save.uncheck();
 if(!await latest.isEnabled())throw Error('Request-only mode should allow pinned configuration');
 await save.check();
 let sent;
 await page.route('**/api/documents/*/reprocess-fields',async route=>{
  if(route.request().method()!=='POST')return route.continue();
  sent=route.request().postDataJSON();
  return route.fulfill({status:202,json:{guidance_saved_to_profile:true}});
 });
 await workspace.getByRole('button',{name:'Reprocess selected fields',exact:true}).click();
 await workspace.getByText('Guidance saved to this document profile for future runs. Selected fields are queued for extraction.',{exact:true}).waitFor();
 if(!sent?.save_to_profile||!sent.use_latest_config||!sent.instruction)throw Error('Reusable guidance not sent to API');
 await mkdir(path.join(root,'data/field-ui'),{recursive:true});
 await page.screenshot({path:path.join(root,'data/field-ui/reprocess.png'),fullPage:false});
 await writeFile(path.join(root,'data/field-ui/checks.json'),JSON.stringify({profileSchemaDraft:true,selectedFieldUI:true,reusableGuidanceDefault:true,requestOnlyOption:true,correctSubmission:true,realProviderCalls:0,errors},null,2));
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: profile draft, field controls, reusable guidance default, request-only option, correct intercepted submission, no browser errors. No extraction was queued.');
} finally {await browser.close();}
